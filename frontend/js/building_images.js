function getBuildingCoverImage(bname, fallback) {
    if (!bname) return fallback || 'img/太和殿-明清-北京故宫/taihe_01.jpg';
    
    const processImagePath = (path) => {
        if (!path) return null;
        if (path.startsWith('/img/')) {
            return path.substring(1);
        }
        if (path.startsWith('img/')) {
            return path;
        }
        return path;
    };
    
    // 首先检查是否有本地图片
    if (BUILDING_IMAGES[bname] && BUILDING_IMAGES[bname].length > 0) {
        return BUILDING_IMAGES[bname][0];
    }
    
    // 检查模糊匹配
    for (const key in BUILDING_IMAGES) {
        if (bname.includes(key) || key.includes(bname)) {
            return BUILDING_IMAGES[key][0];
        }
    }
    
    // 处理外部URL或placeholder
    const processedFallback = processImagePath(fallback);
    if (processedFallback && processedFallback !== 'img/index/lishi.jpg' && processedFallback !== 'img/placeholder.jpg') {
        return processedFallback;
    }
    
    // 如果fallback是placeholder或不存在，返回一个默认的可用图片
    return 'img/太和殿-明清-北京故宫/taihe_01.jpg';
}

function getBuildingImages(bname) {
    if (!bname) return [];
    if (BUILDING_IMAGES[bname]) return BUILDING_IMAGES[bname];
    for (const key in BUILDING_IMAGES) {
        if (bname.includes(key) || key.includes(bname)) {
            return BUILDING_IMAGES[key];
        }
    }
    return [];
}


        pid = PROVINCE_MAP.get(province_name, 1)
        did = DYNASTY_MAP.get(dynasty_name, 1)
        
        Scenery.objects.create(
            sid=next_sid,
            sname=building['name'],
            pid=pid,
            did=did,
            label=1,
            introduction=building['desc'][:500],
            category='古建筑',
            city=building['city'],
            latitude=building['lat'],
            longitude=building['lng']
        )
        
        next_sid += 1
        building_count += 1
        
